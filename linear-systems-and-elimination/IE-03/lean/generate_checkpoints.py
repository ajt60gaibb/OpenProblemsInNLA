#!/usr/bin/env python3
"""Materialize the staged rational Schur complements for the Lean certificate."""

import argparse
import ast
from fractions import Fraction
from hashlib import sha256
from math import lcm
from pathlib import Path

PROJECT = Path(__file__).resolve().parent
SOURCE = PROJECT.parents[2] / "references/andia-ie03-2026-10-31/verify_construction.py"
SOURCE_HASH = "f9cd356dbfdb0505737d24155be86eb09d47a8ccfdb7d1808b31ca1e3c27a5b1"
ORDERS = (16, 64, 256, 1024, 4096)
COUNTS = (10, 16, 22, 28, 48)


def pivot_lists():
    source = SOURCE.read_bytes()
    if sha256(source).hexdigest() != SOURCE_HASH:
        raise ValueError(f"source hash mismatch: {SOURCE}")
    positions, = (
        ast.literal_eval(statement.value)
        for statement in ast.parse(source).body
        if isinstance(statement, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "LOCAL_PIVOTS"
                for target in statement.targets)
    )
    if tuple(map(len, positions)) != COUNTS:
        raise ValueError("unexpected pivot counts")
    return positions


def walsh_sign(i, j):
    return (-1) ** (i & j).bit_count()


def lift_four(matrix):
    return [
        [value * walsh_sign(i, j) for value in row for j in range(4)]
        for row in matrix
        for i in range(4)
    ]


def eliminate(matrix, r, c):
    pivot = matrix[r][c]
    if pivot == 0 or any(abs(value) > abs(pivot) for row in matrix for value in row):
        raise ValueError(f"illegal pivot {(r, c)} in order {len(matrix)}")
    return [
        [
            value - row[c] * matrix[r][j] / pivot
            for j, value in enumerate(row)
            if j != c
        ]
        for i, row in enumerate(matrix)
        if i != r
    ]


def encode_row(row, denominator):
    word = 0
    for column, value in enumerate(row):
        numerator = int(value * denominator)
        slot = numerator + 32768
        if not 0 <= slot < 65536:
            raise ValueError(f"numerator exceeds 16-bit slot: {numerator}")
        word |= slot << (16 * column)
    return hex(word)


def render_checkpoint(name, matrix):
    denominator = lcm(*(value.denominator for row in matrix for value in row))
    words = ["    " + encode_row(row, denominator) for row in matrix]
    entries = "#[\n" + ",\n".join(words) + "\n  ]" if words else "#[]"
    return (
        f"def {name} : Checkpoint where\n"
        f"  denominator := {denominator}\n"
        f"  rows := {entries}"
    )


def render_phase(order, states):
    names = [f"stage{order}_{i}" for i in range(len(states))]
    lines = [
        "import NLA.IE03.Certificate.Checkpoint",
        "",
        "/-! Exact checkpoint inputs generated by `generate_checkpoints.py`. -/",
        "",
        "namespace NLA.IE03.Certificate",
        "",
        *(render_checkpoint(name, matrix) + "\n"
          for name, matrix in zip(names, states, strict=True)),
        "end NLA.IE03.Certificate",
        "",
    ]
    return "\n".join(lines)


def render_checks(order, positions, states):
    first = f"stage{order}_0"
    last = f"stage{order}_{len(positions)}"
    names = [f"checked_{i}" for i in range(len(positions))]
    first_size = len(states[0])
    final_size = len(states[-1])
    growth = max(abs(states[i][r][c]) for i, (r, c) in enumerate(positions))
    if growth.denominator != 1:
        raise ValueError(f"expected an integral phase maximum, got {growth}")

    lines = [
        f"import NLA.IE03.Certificate.Phase{order}",
        "import NLA.IE03.Certificate.Sound",
        "",
        "/-! Kernel checks for the generated active squares in this phase. -/",
        "",
        "namespace NLA.IE03.Certificate",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 3000000",
        "",
    ]
    for i, (r, c) in enumerate(positions):
        next_size = first_size - i - 1
        lines += [
            f"private theorem {names[i]} :",
            f"    stepOK {next_size} stage{order}_{i} stage{order}_{i + 1} {r} {c} = true := by",
            "  decide +kernel",
            "",
        ]

    steps = [f"({r}, {c}, stage{order}_{i + 1})" for i, (r, c) in enumerate(positions)]
    lines += [
        "private def steps : List Step := [",
        ",\n".join("  " + ", ".join(steps[i:i + 3]) for i in range(0, len(steps), 3)),
        "]",
        "",
        f"theorem phase{order} :",
        f"    Trace {first_size} {first}.entries {final_size} {last}.entries {growth} := by",
        f"  have checked : traceOK {first_size} {first} steps = true := by",
        "    simp only [steps, traceOK, Bool.true_and,",
        ",\n".join("      " + ", ".join(names[i:i + 6]) for i in range(0, len(names), 6)) + "]",
        f"  have growth : peak {first} steps = {growth} := by decide +kernel",
        "  simpa only [growth, Rat.cast_ofNat] using! trace_sound checked",
        "",
        "end NLA.IE03.Certificate",
        "",
    ]
    return "\n".join(lines)


def write_or_check(path, data, check):
    if check:
        if path.read_text() != data:
            raise SystemExit(f"stale generated input: {path}")
    else:
        path.write_text(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare without writing files")
    args = parser.parse_args()

    stages = pivot_lists()
    matrix = [[Fraction(walsh_sign(i, j)) for j in range(16)] for i in range(16)]
    for order, positions in zip(ORDERS, stages, strict=True):
        if order != 16:
            matrix = lift_four(matrix)
        states = [matrix]
        for r, c in positions:
            matrix = eliminate(matrix, r, c)
            states.append(matrix)
        path = PROJECT / "NLA/IE03/Certificate" / f"Phase{order}.lean"
        write_or_check(path, render_phase(order, states), args.check)
        checks = path.with_name(f"Phase{order}Checks.lean")
        write_or_check(checks, render_checks(order, positions, states), args.check)
        print(f"Phase {order}: {len(states) - 1} pivots, {len(states)} checkpoints")


if __name__ == "__main__":
    main()
